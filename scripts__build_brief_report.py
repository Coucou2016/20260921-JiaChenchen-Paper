def FIG(key: str, caption: str) -> str:
    return f'<figure>\n{FIGIMG[key]}\n<figcaption>{caption}</figcaption>\n</figure>\n'


def TAB(num: int, caption: str) -> str:
    t = re.sub(r"<caption>.*?</caption>", f"<caption>{caption}</caption>",
               TABBLOCK[num], flags=re.S)
    return t


